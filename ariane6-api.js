function encodeBase10(w) {
    return w.toUpperCase().split('')
        .map(c => c.charCodeAt(0) - 64)
        .filter(n => n >= 1 && n <= 26)
        .join('.');
}

function sommeA1Z26(w) {
    return w.toUpperCase().split('')
        .map(c => c.charCodeAt(0) - 64)
        .filter(n => n >= 1 && n <= 26)
        .reduce((a, b) => a + b, 0);
}

function couleur(str) {
    let h = 0x811c9dc5;
    for (let i = 0; i < str.length; i++) {
        h ^= str.charCodeAt(i);
        h = (h * 0x01000193) >>> 0;
    }
    return {
        hex: '#' + (h & 0xFFFFFF).toString(16).padStart(6, '0'),
        rgb: `RGB(${(h >> 16) & 0xFF}, ${(h >> 8) & 0xFF}, ${h & 0xFF})`
    };
}

function sha256(t) {
    return crypto.createHash('sha256').update(t).digest('hex');
}

